def photos(key: str) -> list[dict]:
    rnd = random.Random(key)
    out = []
    for name, lat, lon, day, hm, n in TRIPS[key][1]:
        h, m = map(int, hm.split(":"))
        for i in range(n):
            mm = h * 60 + m + i * 7
            out.append({"lat": round(lat + rnd.gauss(0, 0.0007), 5), "lon": round(lon + rnd.gauss(0, 0.0009), 5),
                        "day": day, "t": f"{mm // 60:02d}:{mm % 60:02d}", "place": name})
    return out
