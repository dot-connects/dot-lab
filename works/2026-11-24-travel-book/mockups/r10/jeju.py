def xy(p): return (round(14 + (p[0]-126.15)*329.3, 1), round(8 + (33.57-p[1])*394.7, 1))
def smooth(pts):
    q = [xy(p) for p in pts]; n = len(q)
    mid = lambda a, b: (round((a[0]+b[0])/2, 1), round((a[1]+b[1])/2, 1))
    d = "M%g %g" % mid(q[-1], q[0])
    for i in range(n):
        m = mid(q[i], q[(i+1) % n]); d += "Q%g %g %g %g" % (q[i][0], q[i][1], m[0], m[1])
    return d + "Z"
