function hash(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

/** {type, line} for a creature id and kind, fixed per id */
export function cardText(id, kind) {
  const h = hash(String(id)), t = TYPES[kind] || TYPES.pokemon, l = LINES[kind] || LINES.pokemon;
  return { type: t[h % t.length], line: l[(h >>> 8) % l.length] };
}
