"""Writes the four widget layouts (main / wide x light ink / dark ink) so the two inks never drift apart.

Run from app/: python tools/gen_widget_layouts.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "app/src/main/res/layout"
INKS = {
    "light": {"ink": "#FFFFFFFF", "shadow": 'android:shadowColor="#A6000000" android:shadowDy="1" android:shadowRadius="6"'},
    "dark": {"ink": "#FF16191C", "shadow": ""},
}


def text(id_, size, bold=True, extra=""):
    return (f'<TextView android:id="@+id/{id_}" android:layout_width="wrap_content" android:layout_height="wrap_content" '
            f'android:maxLines="1" android:ellipsize="end" android:textColor="@INK@" android:textSize="{size}sp" '
            f'{"android:textStyle=\"bold\" " if bold else ""}@SHADOW@ {extra}/>')


def button(id_, width, extra=""):
    return (f'<TextView android:id="@+id/{id_}" android:layout_width="{width}" android:layout_height="48dp" {extra} '
            'android:gravity="center" android:drawablePadding="4dp" android:paddingHorizontal="6dp" android:maxLines="1" '
            'android:textColor="@INK@" android:textSize="14sp" android:textStyle="bold" />')


HEADER = f'''<LinearLayout android:layout_width="match_parent" android:layout_height="wrap_content" android:orientation="horizontal">
            {text("place", 12.5, extra='android:layout_weight="1"').replace('android:layout_width="wrap_content"', 'android:layout_width="0dp"', 1)}
            {text("time", 12.5, extra='android:layout_marginStart="6dp"')}
        </LinearLayout>
        <TextView android:id="@+id/tag" android:layout_width="wrap_content" android:layout_height="wrap_content" android:layout_marginTop="4dp"
            android:paddingHorizontal="8dp" android:paddingVertical="2dp" android:textColor="#FF16191C" android:textSize="12sp" android:textStyle="bold" />'''

ROW = f'''<LinearLayout android:id="@+id/row" android:layout_width="match_parent" android:layout_height="wrap_content" android:gravity="bottom" android:orientation="horizontal">
            <ImageView android:id="@+id/mark" android:layout_width="wrap_content" android:layout_height="wrap_content" android:contentDescription="@null" />
            <LinearLayout android:layout_width="0dp" android:layout_height="wrap_content" android:layout_weight="1" android:layout_marginStart="10dp" android:orientation="vertical">
                {text("pz", 21)}
                {text("line1", 14)}
                {text("line2", 13, bold=False)}
            </LinearLayout>
        </LinearLayout>'''

SPACER = '<FrameLayout android:layout_width="match_parent" android:layout_height="0dp" android:layout_weight="1" />'

MAIN = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_widget_layouts.py, do not edit. -->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android" android:id="@+id/root"
    android:layout_width="match_parent" android:layout_height="match_parent">
    <ImageView android:id="@+id/panel" android:layout_width="match_parent" android:layout_height="match_parent"
        android:contentDescription="@null" android:scaleType="fitXY" android:src="@drawable/wpanel" />
    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent" android:orientation="vertical" android:padding="10dp">
        {HEADER}
        {SPACER}
        {ROW}
        {SPACER}
        <LinearLayout android:id="@+id/buttons" android:layout_width="match_parent" android:layout_height="wrap_content" android:layout_marginTop="6dp" android:orientation="horizontal">
            {button("b1", "0dp", 'android:layout_weight="1"')}
            {button("b2", "0dp", 'android:layout_weight="1" android:layout_marginStart="6dp"')}
            {button("b3", "0dp", 'android:layout_weight="1" android:layout_marginStart="6dp"')}
        </LinearLayout>
        <LinearLayout android:id="@+id/row2" android:layout_width="match_parent" android:layout_height="wrap_content" android:layout_marginTop="8dp" android:gravity="bottom" android:orientation="horizontal">
            <ImageView android:id="@+id/mark2" android:layout_width="wrap_content" android:layout_height="wrap_content" android:contentDescription="@null" />
            <LinearLayout android:layout_width="0dp" android:layout_height="wrap_content" android:layout_weight="1" android:layout_marginStart="10dp" android:orientation="vertical">
                {text("r2a", 13.5)}
                {text("r2b", 12.5, bold=False)}
            </LinearLayout>
        </LinearLayout>
    </LinearLayout>
</FrameLayout>
'''

WIDE = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_widget_layouts.py, do not edit. -->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android" android:id="@+id/root"
    android:layout_width="match_parent" android:layout_height="match_parent">
    <ImageView android:id="@+id/panel" android:layout_width="match_parent" android:layout_height="match_parent"
        android:contentDescription="@null" android:scaleType="fitXY" android:src="@drawable/wpanel" />
    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent" android:orientation="horizontal" android:padding="10dp">
        <LinearLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="1" android:orientation="vertical">
            {HEADER}
            {SPACER}
            {ROW}
        </LinearLayout>
        <LinearLayout android:id="@+id/buttons" android:layout_width="wrap_content" android:layout_height="match_parent" android:layout_marginStart="10dp" android:gravity="bottom" android:orientation="vertical">
            {button("b1", "112dp")}
            {button("b2", "112dp", 'android:layout_marginTop="6dp"')}
            {button("b3", "112dp", 'android:layout_marginTop="6dp"')}
        </LinearLayout>
    </LinearLayout>
</FrameLayout>
'''

for name, body in {"w_main": MAIN, "w_wide": WIDE}.items():
    for ink, v in INKS.items():
        (OUT / f"{name}_{ink}.xml").write_text(body.replace("@INK@", v["ink"]).replace("@SHADOW@", v["shadow"]), encoding="utf-8")
print("ok")
